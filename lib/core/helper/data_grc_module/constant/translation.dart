  **أ)** إعادة هندسة عكسية، أو تغيير، أو تعديل، أو إنشاء أعمال مشتقة، أو فك تشفير، أو استخلاص الشفرة من خدماتنا؛

  **ب)** إرسال، أو تخزين، أو نقل الفيروسات أو أي برامج ضارة أخرى عبر خدماتنا؛

  **ج)** الحصول على الوصول غير المصرح به أو محاولة الحصول على الوصول غير المصرح به إلى خدماتنا أو أنظمتنا؛

  **د)** التدخل في سلامة، وأمان، وسرية، ونزاهة، وتوفر، وأداء خدماتنا؛

  **هـ)** إنشاء حسابات لخدماتنا عبر وسائل غير مصرح بها أو وسائل آلية؛

  **و)** جمع معلومات عن مستخدمينا أو عنهم بأي طريقة غير مشروعة أو غير مصرح بها؛

  **ز)** بيع، أو إعادة بيع، أو تأجير، أو فرض رسوم على خدماتنا أو البيانات التي تم الحصول عليها منا أو من خدماتنا بطرق غير مصرح بها؛

  **ح)** توزيع أو توفير خدماتنا عبر شبكة يمكن استخدامها من قبل أجهزة متعددة في نفس الوقت، ما لم يتم ذلك بالطرق المصرح بها من خلال الأدوات التي قدمناها بشكل صريح عبر خدماتنا؛

  **ط)** إنشاء برامج أو واجهات برمجة تعمل بشكل مشابه لخدماتنا وتقدمها للاستخدام من قبل أطراف ثالثة بطرق غير مصرح بها؛

  **ي)** إساءة استخدام أي قنوات للإبلاغ، مثل تقديم تقارير أو استئنافات زائفة أو بدون أساس.

