- تُعفينا، وشركاتنا التابعة، وشركاءنا، ومدراءنا، وموظفينا، وشركاءنا، ووكلائنا (معًا، "أطراف Knowticed") من أي ادعاء، شكوى، سبب من الأسباب، نزاع، نزاع، أو أضرار (معًا "المطالبة")، معروفة أو غير معروفة، تتعلق بالمطالبة التي لديك ضد أي أطراف ثالثة.
- لا يتم تعديل حقوقك فيما يتعلق بأطراف Knowticed بسبب الإخلاء المذكور أعلاه إذا لم تسمح به القوانين في بلدك أو إقليم إقامتك وفقًا لاستخدامك لخدماتنا.
