   **د)** التنكر في شخص آخر.

   **هـ)** تنطوي على إرسال رسائل غير قانونية أو غير مسموح بها مثل الرسائل الجماعية، والرسائل التلقائية، والاتصال التلقائي وما شابه ذلك.

   **و)** تنطوي على أي استخدام غير شخصي لخدماتنا ما لم يكن مصرحًا به غير ذلك من قبلنا.

