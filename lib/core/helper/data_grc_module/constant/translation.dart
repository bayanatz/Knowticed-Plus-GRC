# التراخيص
- لا تدعي Knowticed ملكية المعلومات التي تقدمها لحساب Knowticed الخاص بك أو من خلال خدماتنا. يجب أن تكون لديك الحقوق اللازمة في هذه المعلومات التي تقدمها لحساب Knowticed الخاص بك أو من خلال خدماتنا، ويجب أن تكون لديك الحق في منح الحقوق والتراخيص وفقًا لشروطنا.

- نحن نمتلك جميع حقوق النشر والعلامات التجارية والنطاقات والشعارات والشكل التجاري وأسرار الصناعة وبراءات الاختراع وحقوق الملكية الفكرية الأخرى المرتبطة بخدماتنا. لا يجوز لك استخدام حقوق النشر لدينا أو العلامات التجارية (أو أي علامات مماثلة) أو النطاقات أو الشعارات أو الشكل التجاري أو أسرار الصناعة أو براءات الاختراع أو حقوق الملكية الفكرية الأخرى ما لم تحصل على إذن صريح منا وبموجب إرشادات العلامة التجارية لدينا. يجوز لك استخدام علامات التجارية التابعة لشركاتنا التابعة فقط بإذنها، بما في ذلك الاستخدام المصرح به في أي إرشادات علامة تجارية منشورة.

- من أجل تشغيل وتوفير خدماتنا، فإنك تمنح Knowticed ترخيصًا عالميًا وغير حصري وخاليًا من الروابط وقابلًا للترخيص الفرعي وقابلًا للنقل لاستخدام واستنساخ وتوزيع وإنشاء أعمال مشتقة من وعرض وأداء المعلومات (بما في ذلك المحتوى) الذي تقوم بتحميله أو تقديمه أو تخزينه أو إرساله أو استلامه على خدماتنا. الحقوق التي تمنحها في هذا الترخيص هي للغرض المحدود من تشغيل وتوفير خدماتنا (مثل السماح لنا بعرض صورة ملف تعريفك ونقل رسائلك وتخزين رسائلك غير المستلمة على خوادمنا لمدة تصل إلى 30 يومًا أثناء محاولتنا توصيلها).

- نحن نمنحك ترخيصًا محدودًا وقابلًا للإلغاء وغير حصري وغير قابل للترخيص الفرعي وغير قابل للنقل لاستخدام خدماتنا، وفقًا لشروطنا ووفقًا لها. هذا الترخيص هو للغرض الوحيد من تمكينك من استخدام خدماتنا بالطريقة المسموح بها في شروطنا. لا يتم منحك تراخيص أو حقوق ضمنيًا أو بأي طريقة أخرى، ما لم يتم منحك تراخيص وحقوق صراحة.
# الإبلاغ عن انتهاك حقوق الملكية الفكرية للأطراف الثالثة

للإبلاغ عن ادعاءات انتهاك حقوق الملكية الفكرية للأطراف الثالثة، يرجى زيارة سياسة الملكية الفكرية الخاصة بنا. قد نتخذ إجراءات تجاه حسابك، بما في ذلك تعطيله أو إيقافه، إذا كنت تنتهك بوضوح أو بشكل جاد أو متكرر حقوق الملكية الفكرية للآخرين أو إذا كانت هناك ضرورة قانونية لذلك. ستتم عملية تعطيل أو إيقاف حسابك وفقًا لقسم "إنهاء الخدمة" الموضح أدناه.

