   **أ)** تكون غير قانونية، مبتذلة، مُجدرة للكراهية، تهديدية، مزعجة، كارهة، مسيئة عنصريًا أو عرقيًا، أو تحرض أو تشجع على سلوك غير قانوني أو غير مناسب بأي شكل من الأشكال، مثل تعزيز الجرائم العنيفة أو تعريض الأطفال أو الآخرين للخطر أو استغلالهم، أو تنسيق الضرر

   **ب)** تكون غير قانونية، مشينة، مجدرة للكراهية، مسيئة، تهديدية، تخويفية، كارهة، عنصرية أو تعرقية، أو تحرض أو تشجع على سلوك يعتبر غير قانوني أو غير مناسب بأي شكل من الأشكال، مثل الترويج لجرائم عنيفة، تعريض الأطفال أو الآخرين للخطر أو استغلالهم، أو تنسيق الضرر.

